    public void refreshTable() {
        DefaultTableModel model = (DefaultTableModel) tblStudents.getModel();
        model.setRowCount(0);

        for (StudentProfile sp : business.getStudentDirectory().getStudentList()) {
            UserAccount ua = business.getUserAccountDirectory().findByProfile(sp);
            Object[] row = new Object[5];
            row[0] = sp.getPerson().getPersonId();     // the NUID finds the student again on selection
            row[1] = sp.getPerson().getName();
            row[2] = sp.getProgram();
            row[3] = sp.getPerson().getEmail();
            row[4] = ua == null ? "Not signed up" : ua.getUserLoginName();
            model.addRow(row);
        }
    }    

