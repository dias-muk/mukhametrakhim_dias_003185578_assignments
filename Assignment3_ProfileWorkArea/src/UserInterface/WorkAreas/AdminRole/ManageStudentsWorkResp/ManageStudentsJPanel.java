    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        int row = tblStudents.getSelectedRow();
        if (row < 0) {
            JOptionPane.showMessageDialog(this, "Please select a student first.",
                    "No student selected", JOptionPane.WARNING_MESSAGE);
            return;
        }
        String nuid = (String) tblStudents.getValueAt(row, 0);
        StudentProfile student = business.getStudentDirectory().findStudent(nuid);
        AdministerStudentJPanel detail = new AdministerStudentJPanel(business, student, CardSequencePanel);
        CardSequencePanel.add("StudentDetail", detail);
        ((java.awt.CardLayout) CardSequencePanel.getLayout()).next(CardSequencePanel);
    }//GEN-LAST:event_btnUpdateActionPerformed

