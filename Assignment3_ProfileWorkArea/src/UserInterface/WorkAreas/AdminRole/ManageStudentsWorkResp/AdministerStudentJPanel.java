        /** Fills the form from the selected student. */
    private void showStudent() {
        Person person = student.getPerson();
        lblTitle.setText("Student: " + person.getName());
        fieldNuid.setText(person.getPersonId());
        fieldName.setText(person.getName());
        fieldEmail.setText(person.getEmail());
        fieldPhone.setText(person.getPhone());
        fieldProgram.setText(student.getProgram());
        UserAccount ua = business.getUserAccountDirectory().findByProfile(student);
        fieldAccount.setText(ua == null ? "Not signed up" : ua.getUserLoginName());
    }

    /** The fields every student needs, checked top to bottom. */
    private boolean detailsAreFilled() {
        return Validator.isFilled(this, fieldNuid, "NUID")
                && Validator.isFilled(this, fieldName, "Name")
                && Validator.isFilled(this, fieldEmail, "Email")
                && Validator.isFilled(this, fieldPhone, "Phone")
                && Validator.isFilled(this, fieldProgram, "Program");
    }

    /** Copies the form into the person and the student profile. */
    private void copyDetailsInto(Person person, StudentProfile sp) {
        person.setName(fieldName.getText().trim());
        person.setEmail(fieldEmail.getText().trim());
        person.setPhone(fieldPhone.getText().trim());
        sp.setProgram(fieldProgram.getText().trim());
    }

    private void addStudent() {
        if (!detailsAreFilled()) {
            return;
        }
        String nuid = fieldNuid.getText().trim();
        if (business.getPersonDirectory().findPerson(nuid) != null) {
            JOptionPane.showMessageDialog(this, "NUID " + nuid + " is already registered.",
                    "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        Person person = business.getPersonDirectory().newPerson(nuid, fieldName.getText().trim());
        StudentProfile sp = business.getStudentDirectory().newStudentProfile(person);
        copyDetailsInto(person, sp);
        JOptionPane.showMessageDialog(this, "Student added. They can now sign up with NUID " + nuid + ".",
                "Student added", JOptionPane.INFORMATION_MESSAGE);
        goBack();
    }

    private void saveChanges() {
        if (!detailsAreFilled()) {
            return;
        }
        copyDetailsInto(student.getPerson(), student);
        showStudent();
        JOptionPane.showMessageDialog(this, "Student updated.", "Saved", JOptionPane.INFORMATION_MESSAGE);
    }

    /** Removes this screen and shows the student list again, reloaded. */
    private void goBack() {
        CardSequencePanel.remove(this);
        java.awt.Component[] stack = CardSequencePanel.getComponents();
        java.awt.Component below = stack[stack.length - 1];
        if (below instanceof ManageStudentsJPanel) {
            ((ManageStudentsJPanel) below).refreshTable();
        }
        ((java.awt.CardLayout) CardSequencePanel.getLayout()).previous(CardSequencePanel);
    }

