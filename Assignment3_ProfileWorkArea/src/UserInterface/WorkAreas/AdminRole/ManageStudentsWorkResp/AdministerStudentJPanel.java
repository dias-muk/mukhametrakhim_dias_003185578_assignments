    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        UserAccount ua = business.getUserAccountDirectory().findByProfile(student);
        String message = "Delete " + student.getPerson().getName() + "?"
                + (ua == null ? "" : " Their login \"" + ua.getUserLoginName() + "\" will be deleted too.");
        int answer = JOptionPane.showConfirmDialog(this, message, "Confirm delete",
                JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE);
        if (answer != JOptionPane.YES_OPTION) {
            return;
        }
        business.deleteProfile(student);
        JOptionPane.showMessageDialog(this, "Student deleted.", "Deleted", JOptionPane.INFORMATION_MESSAGE);
        goBack();
    }//GEN-LAST:event_btnDeleteActionPerformed

